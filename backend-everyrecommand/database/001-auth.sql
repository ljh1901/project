-- User 테이블 
CREATE TABLE TB_EVRC_USERS(
	SEQ_TB_EVRC_USERS INT,
	USER_ID VARCHAR(20) NOT NULL UNIQUE,
	USER_PWD VARCHAR(50) NOT NULL,
	USER_NAME VARCHAR(20) NOT NULL,
	USER_BRTH DATE NOT NULL,
	USER_CRET TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	USER_UPET TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	USER_EMIL VARCHAR(40) UNIQUE,
	USER_PRFID VARCHAR(40) UNIQUE,
	CONSTRAINT PK_TB_EVRC_USERS PRIMARY KEY(SEQ_TB_EVRC_USERS)
);
create sequence SEQ_TB_EVRC_USERS start with 1;
COMMENT ON TABLE TB_EVRC_USERS IS '유저 테이블';
COMMENT ON COLUMN TB_EVRC_USERS.SEQ_TB_EVRC_USERS IS '사용자 순번';
COMMENT ON COLUMN TB_EVRC_USERS.USER_ID IS '사용자 아이디';
COMMENT ON COLUMN TB_EVRC_USERS.USER_PWD IS '사용자 비밀번호';
COMMENT ON COLUMN TB_EVRC_USERS.USER_NAME IS '사용자 이름';
COMMENT ON COLUMN TB_EVRC_USERS.USER_BRTH IS '사용자 생년월일';
COMMENT ON COLUMN TB_EVRC_USERS.USER_CRET IS '사용자 생성일';
COMMENT ON COLUMN TB_EVRC_USERS.USER_UPET IS '사용자 수정일';
COMMENT ON COLUMN TB_EVRC_USERS.USER_EMIL IS '사용자 이메일';
COMMENT ON COLUMN TB_EVRC_USERS.USER_PRFID IS '사용자 폰번호';

